-- Exploring Address Table (customers location)

SELECT *
FROM ADDRESS;

SELECT DISTRICT, COUNT(*) AS COUNT_D 
FROM ADDRESS
GROUP BY DISTRICT 
ORDER BY COUNT_D DESC;

SELECT DISTRICT, COUNT(*) AS COUNT_D 
FROM ADDRESS
GROUP BY DISTRICT
HAVING COUNT(*) > 5 
ORDER BY COUNT_D DESC;

SELECT ADDRESS_ID, ADDRESS, DISTRICT, POSTAL_CODE, ADDRESS.CITY_ID, CITY
FROM ADDRESS, CITY
WHERE ADDRES.CITY_ID = CITY.CITY_ID;

SELECT DISTRICT, COUNT(CITY) AS CITY_COUNT
FROM (SELECT DISTINCT DISTRICT, CITY FROM ADDRESS, CITY WHERE ADDRESS.CITY_ID = CITY.CITY_ID) AS Joined
GROUP BY DISTRICT 
ORDER BY CITY_COUNT DESC;

SELECT DISTRICT, COUNT(*) N_CUSTOMERS 
FROM (SELECT CUSTOMER_ID, FIRST_NAME, LAST_NAME, DISTRICT
FROM CUSTOMER, ADDRESS
WHERE CUSTOMER.ADDRESS_ID = ADDRESS.ADDRESS_ID) AS Joined
GROUP BY DISTRICT 
ORDER BY N_CUSTOMERS DESC;

-- Exploring Film Table (offering space)
SELECT *
FROM FILM;

SELECT RATING, COUNT(*) 
FROM FILE
GROUP BY RATING 
ORDER BY RATING;

SELECT rating, ROUND(AVG(length), 2) AS avg_leng, ROUND(AVG(rental_rate), 2) AS avg_rate
FROM FILM
GROUP BY RATING
ORDER BY RATING;

SELECT RENTAL_DURATION, ROUND(AVG(LENGTH), 2) AS AVG_LENG, ROUND(AVG(RENTAL_RATE), 2) AS AVG_RATE
FROM FILM
GROUP BY RENTAL_DURATION
ORDER BY RENTAL_DURATION;

SELECT RENTAL_DURATION, COUNT(*) AS COUNT_FILMS, 
	ROUND(AVG(length), 2) AS avg_leng,
	ROUND(STDDEV(length), 2) AS std_len,
	ROUND(AVG(rental_rate), 2) AS avg_rate,
	ROUND(STDDEV(rental_rate), 2) AS std_rate
FROM FILM
WHERE RATING IN ('PG', 'PG-13')
GROUP BY RENTAL_DURATION
ORDER BY RENTAL_DURATION;

SELECT RENTAL_DURATION, COUNT(*) AS COUNT_FILMS,
	ROUND(STDDEV(length)/AVG(length),2) AS NSD_LEN,
	ROUND(STDDEV(rental_rate)/AVG(rental_rate),2) AS NSD_RATE
FROM FILM
WHERE RATING IN ('PG', 'PG-13')
GROUP BY RENTAL_DURATION
HAVING STDDEV(RENTAL_RATE)/AVG(RENTAL_RATE) < 0.5
ORDER BY RENTAL_DURATION;

SELECT FILM.FILM_ID, TITLE, FILM_CATEGORY.CATEGORY_ID, NAME
FROM FILM, FILM_CATEGORY, CATEGORY
WHERE FILM.FILM_ID = FILM_CATEGORY.FILM_ID
AND FILM_CATEGORY.CATEGORY_ID = CATEGORY.CATEGORY_ID;

