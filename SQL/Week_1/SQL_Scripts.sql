);

CREATE TABLE people.location (
    ID_BIGSERIEL PRIMARY KEY,
    COUNTRY varchar(50),
    CITY varchar(50),
    STREET_NAME varchar(50),
    STREET_NUMBER int,
    POSTAL_CODE varchar(50)
);

