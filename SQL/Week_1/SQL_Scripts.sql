### GROUP BY

-- Group by on a single column
SELECT CAR_MAKE, COUNT(*) 
FROM PEOPLE.CAR
GROUP BY CAR_MAKE;

SELECT CAR_MAKE, COUNT(*) 
FROM PEOPLE.CAR
GROUP BY CAR_MAKE
ORDER BY COUNT(*) DESC;

SELECT CAR_MAKE, COUNT(DISTINCT CAR_MODEL)
FROM PEOPLE.CAR
GROUP BY CAR_MAKE
ORDER BY COUNT(DISTINCT CAR_MODEL) DESC; 

-- Group by on two columns
SELECT CAR_MAKE, CAR_MODEL, AVG(PRICE)
FROM PEOPLE.CAR
GROUP BY CAR_MAKE, CAR_MODEL;

SELECT CAR_MAKE, CAR_MODEL, ROUND(AVG(PRICE), 2)
FROM PEOPLE.CAR
GROUP BY CAR_MAKE, CAR_MODEL;

SELECT CAR_MAKE, CAR_MODEL, ROUND(AVG(PRICE), 2)
FROM PEOPLE.CAR
GROUP BY CAR_MAKE, CAR_MODEL
ORDER BY CAR_MAKE, CAR_MODEL;

SELECT CAR_MAKE, CAR_MODEL, MAX(PRICE)
FROM PEOPLE.CAR
GROUP BY CAR_MAKE, CAR_MODEL
ORDER BY CAR_MAKE, CAR_MODEL;

-- HAVING
SELECT CAR_MAKE, CAR_MODEL, AVG(PRICE)
FROM PEOPLE.CAR
GROUP BY CAR_MAKE, CAR_MODEL
HAVING AVG(PRICE) < 100000;

SELECT CAR_MAKE, CAR_MODEL, ROUND(AVG(PRICE), 2)
FROM PEOPLE.CAR 
GROUP BY CAR_MAKE, CAR_MODEL 
HAVING AVG(PRICE) < 100000;

SELECT CAR_MAKE, CAR_MODEL, ROUND(AVG(PRICE), 2)
FROM PEOPLE.CAR
GROUP BY CAR_MAKE, CAR_MODEL 
HAVING AVG(PRICE) < 100000
ORDER BY CAR_MAKE, CAR_MODEL;

-- HAVING vs WHERE
SELECT CAR_MAKE, COUNT(*) 
FROM PEOPLE.CAR 
WHERE CAR_YEAR > 2000
GROUP BY CAR_MAKE;

SELECT CAR_MAKE, COUNT(*) 
FROM PEOPLE.CAR
WHERE CAR_YEAR > 2000
GROUP BY CAR_MAKE 
HAVING COUNT(*) > 100;

SELECT CAR_MAKE, COUNT(*) 
FROM PEOPLE.CAR 
WHERE CAR_YEAR > 2000
GROUP BY CAR_MAKE HAVING COUNT(*) BETWEEN 50 AND 100;







 







