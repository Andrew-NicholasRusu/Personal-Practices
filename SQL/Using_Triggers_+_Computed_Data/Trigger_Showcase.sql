CREATE SCHEMA shop_db;
USE shop_db;

CREATE TABLE PRODUCTS (
	PRODUCT_ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    PRICE DECIMAL(10, 2) NOT NULL,
    STOCK INT NOT NULL DEFAULT 0
);

CREATE TABLE ORDER_ITEMS (
	ITEM_ID INT AUTO_INCREMENT PRIMARY KEY,
    PRODUCT_ID INT NOT NULL,
    QUANTITY INT NOT NULL,
    UNIT_PRICE DECIMAL(10, 2) NOT NULL,
    LINE_TOTAL DECIMAL (12, 2) GENERATED ALWAYS AS (QUANTITY * UNIT_PRICE) STORED,
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

CREATE TABLE PRICE_AUDIT (
	AUDIT_ID INT AUTO_INCREMENT PRIMARY KEY, 
    PROUCT_ID INT,
    OLD_PRICE DECIMAL(10, 2),
    NEW_PRICE DECIMAL(10, 2),
    CHANGED_AT DATETIME DEFAULT CURRENT_TIMESTAMP
);

# Trigger A: BEFORE INSERT (validation)
-- Reject bad data with SIGNAL:
DELIMITER $$ 
CREATE TRIGGER TRG_CHECK_QUANTITY
BEFORE INSERT ON ORDER_ITEMS
FOR EACH ROW
BEGIN 
	IF NEW.QUANTITY <= 0 THEN
		SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Quantity must be greater than 0';
	END IF;
END$$
DELIMITER ;

# Trigger B: AFTER INSERT (update another table)
-- Reduce stock when an item is ordered:
DELIMITER $$
CREATE TRIGGER TRG_REDUCE_STOCK
AFTER INSERT ON ORDER_ITEMS
FOR EACH ROW
BEGIN 
	UPDATE PRODUCTS
    SET STOCK = STOCK - NEW.QUANTITY
    WHERE PRODUCT_ID = NEW.PRODUCT_ID;
END$$
DELIMITER ;

# Trigger C: AFTER UPDATE (audit log)
-- Record price changes using both OLD and NEW:
DELIMITER $$
CREATE TRIGGER TRG_PRICE_AUDIT
AFTER UPDATE ON PRODUCTS
FOR EACH ROW 
BEGIN 
	IF OLD.PRICE <> NEW.PRICE THEN
		INSERT INTO PRICE_AUDIT (PRODUCT_ID, OLD_PRICE, NEW_PRICE)
        VALUES (OLD.PRODUCT_ID, OLD.PRICE, NEW.PRICE);
	END IF;
END$$
DELIMITER ;

# Test it:
INSERT INTO PRODUCTS (NAME, PRICE, STOCK)
VALUES ('Notebook', 4.50, 100);

INSERT INTO ORDER_ITEMS (PRODUCT_ID, QUANTITY, UNIT_PRICE)
VALUES (1, 5, 4.50);

SELECT *
FROM PRODUCTS; -- LINE_TOTAL = 22.50 (computed column) 

SELECT * 
FROM ORDER_ITEMS; -- STOCK = 95 (Trigger B)

INSERT INTO ORDER_ITEMS (PRODUCT_ID, QUANTITY, UNIT_PRICE) 
VALUES (1, -2, 4.50); -- ERROR: Quantity must be greater than 0 (Trigger A)

UPDATE PRODUCTS 
SET PRICE = 5.00
WHERE PRODUCT_ID = 1;

SELECT *
FROM PRICE_AUDIT; -- one row logged (Trigger C) 



    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    