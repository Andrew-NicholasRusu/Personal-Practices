DROP PROCEDURE IF EXISTS GET_CUSTOMERS_BY_COUNTRY
DELIMITER $$ 
CREATE PROCEDURE GET_CUSTOMERS_BY_COUNTRY
	@country VARCHAR(50)
AS 
BEGIN
	SELECT CUSTOMER_NAME, CONTACT_NUMBER
    FROM CUSTOMER
    WHERE COUNTRY = @country;
END;
EXEC GET_CUSTOMERS_BY_COUNTRY @country = 'Sri Lanka';
$$
DELIMITER ;
START TRANSACTION;
CALL GET_CUSTOMER_BY_COUNTRY ();

DROP PROCEDURE IF EXISTS REFRESH_CUSTOMER_ORDER_STATS
DELIMITER $$
CREATE PROCEDURE REFRESH_CUSTOMER_ORDER_STATS(P_AS_OF_DATE DATE)
BEGIN
	DELETE FROM CUSTOMER_ORDER_STATS WHERE AS_OF_DATE = P_AS_OF_DATE;
    INSERT INTO CUSTOMER_ORDER_STATS
    SELECT CUSTOMER_ID, COUNT(*), SUM(AMOUNT), P_CAS_OF_DATE
    FROM ORDERS
    WHERE STATUS = 'paid' AND ORDER_DATE <= P_AS_OF_DATE
    GROUP BY CUSTOMER_ID;
END;
$$
DELIMITER ;
START TRANSACTION;
CALL REFRESH_CUSTOMER_ORDER_STATS ();
