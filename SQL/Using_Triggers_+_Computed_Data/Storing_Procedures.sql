-- Audit table for the tirgger to write to
CREATE TABLE EMPLOYEES_AUDIT (
	AUDIT_ID INT AUTO_INCREMENT PRIMARY KEY,
    EMPLOYEE_ID INT,
    OLD_SALARY DECIMAL(10, 2),
    NEW_SALARY DECIMAL(10, 2),
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Trigger
DROP TRIGGER IF EXISTS TRG_EMPLOYEES_AFTER_UPDATE;
DELIMITER $$
CREATE TRIGGER TRG_EMPLOYEES_AFTER_UPDATE
AFTER UPDATE ON EMPLOYEES
FOR EACH ROW
BEGIN
	-- SQL Statements
    IF OLD.SALARY <> NEW.SALARY THEN
		INSERT INTO EMPLOYEES_AUDIT (EMPLOYEE_ID, OLD_SALARY, NEW_SALARY)
        VALUES (OLD.EMPLOYEE_ID, OLD.SALARY, NEW.SALARY);
	END IF;
END;
$$
DELIMITER ;
START TRANSACTION ;
CALL TRIGGER_NAME;

-- Test the trigger by firing it, not calling it.
UPDATE EMPLOYEES SET SALARY = 55000.00 
WHERE EMPLOYEE_ID = 1;

SELECT *
FROM EMPLOYEES_AUDIT;


-- Trigger for Log Insertion Progress
CREATE TABLE LOG (
	LOG_ID INT AUTO_INCREMENT PRIMARY KEY,
    EMPLOYEE_ID INT, 
    ACTION VARCHAR(50)
);

INSERT INTO EMPLOYEES (EMPLOYEE_ID, NAME, SALARY)
VALUES
(1, 'Alex', 33000.00);

CREATE TRIGGER IF NOT EXISTS AFTER_EMPLOYEE_INSERT
DELIMITER $$
CREATE TRIGGER AFTER_EMPLOYEE_INSERT
AFTER INSERT ON EMPLOYEES
FOR EACH ROW 
BEGIN 
	INSERT INTO LOG (EMPLOYEE_ID, ACTION)
    VALUES (NEW.EMPLOYEE_ID, 'INSERT');
END;
$$
DELIMITER ;
START TRANSACTION;
CALL AFTER_EMPLOYEE_INSERT;

SELECT * FROM LOG;






