-- Pseudocode SQL-style function
DROP FUNCTION IF EXISTS ORDER_BAND
DELIMITER $$
CREATE FUNCTION ORDER_BAND(P_AMOUNT NUMERIC) RETURNS TEXT 
AS
BEGIN
	RETURN CASE
		WHEN P_AMOUNT >= 200 THEN 'high'
        WHEN P_AMOUNT >= 100 THEN 'mid'
        WHEN P_AMOUNT >= 50 THEN 'low'
        ELSE 'nothing'
	END;
END;
$$
DELIMITER ;
START TRANSACTION;
CALL ORDER_BAND ();

SELECT ORDER_ID, AMOUNT, ORDER_BAND(AMOUNT) AS AMOUNT_BAND
FROM ORDERS
WHERE STATUS = 'paid';

