CREATE DATABASE IF NOT EXISTS SocialDB
USE SocialDB;

CREATE TABLE SocialDB.Users(
USER_ID INT NOT NULL AUTO_INCREMENT,
	FIRST_NAME VARCHAR(100) NOT NULL,
    LAST_NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    DATE_CREATED DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_ID));
    
DROP TABLE IF EXISTS Images;
    
-- Create the Images tables:
CREATE TABLE Images (
IMAGE_ID INT(11) NOT NULL AUTO_INCREMENT,
	IMAGE_URL VARCHAR(250) NOT NULL,
    DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, 
    PRIMARY KEY (IMAGE_ID));
    
-- Create the SocialDB.Posts
CREATE TABLE SocialDB.Posts (
POST_ID INT NOT NULL AUTO_INCREMENT,
	USER_ID INT NOT NULL,
    POST_TEXT VARCHAR(500) NOT NULL,
    IMAGE_ID INT NULL,
    DATE DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (POST_ID));
    
ALTER TABLE SocialDB.Posts
ADD CONSTRAINT USER_ID
	FOREIGN KEY (USER_ID)
    REFERENCES SocialDB.Users (USER_ID)
    ON DELETE CASCADE
    ON UPDATE CASCADE;
    
-- You set it so that when a User is deleted or updated, those changes will CASCADE into the Posts table.
-- Since there is no reason for us to keep posts for a user who has been deleted, you can also delete the posts associated with them. This is called a CASCADE.

