/**
 * Variables and Datatypes in JavaScript:
    - Variables are used to store data values that can be used and modified in a program. JavaScript supports different data types to handle numbers, text, and other kinds of information.
    - Variables: Declared using var, let, and const to store data values.
 */

// 1. var Keyword:
var n = 5; // used to declare a variable
console.log(n);

var n = 20; // reassigning is allowed
console.log(n);

// 2. let Keyword
let l = 10;
l = 20; // Value can be updated
// let n = 15; // cannot redeclare
console.log(l)

// 3. const Keyword
const c = 100;
// c = 200; This will throw an erro
console.log(c);

